-- ===========================================================================
-- royal_canin.log_sku_match: listing baru dari upload yang seller SKU dan SKU
-- platform-nya belum ada di master, dicocokkan berdasarkan nama produk
-- (DAG process_sku_{channel}, langkah 5). Untuk database yang sudah memakai
-- ddl_royal_canin.sql sebelum tabel ini ditambahkan. Aman dijalankan ulang.
-- ===========================================================================

BEGIN;

DO $do$
BEGIN
    IF to_regclass('royal_canin.log_sku_match') IS NULL THEN
        EXECUTE $sql$CREATE TABLE royal_canin.log_sku_match (
    match_id                     bigint GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    run_id                       bigint,
    upload_id                    varchar(36),
    channel_id                   integer NOT NULL,
    merchant_sku                 text NOT NULL,
    sku_code                     text NOT NULL DEFAULT '',
    seller_sku                   text,
    product_name                 text,
    variation                    text,
    first_order_at               timestamp with time zone,
    last_order_at                timestamp with time zone,
    order_line_count             integer,
    suggested_sku_id             integer,
    suggested_name               text,
    similarity_score             numeric(5,4),
    candidates                   jsonb,
    status                       text NOT NULL DEFAULT 'PENDING',
    resolved_sku_id              integer,
    resolved_by                  text,
    resolved_at                  timestamp with time zone,
    created_at                   timestamp with time zone NOT NULL DEFAULT now(),
    updated_at                   timestamp with time zone NOT NULL DEFAULT now(),
    CONSTRAINT pk_log_sku_match PRIMARY KEY (match_id),
    CONSTRAINT ck_log_sku_match_1 CHECK (status IN ('PENDING','MAPPED','CREATED_NEW')),
    CONSTRAINT ck_log_sku_match_2 CHECK (similarity_score BETWEEN 0 AND 1),
    CONSTRAINT ck_log_sku_match_3 CHECK (status = 'PENDING' OR resolved_sku_id IS NOT NULL),
    CONSTRAINT fk_log_sku_match_run_id FOREIGN KEY (run_id) REFERENCES royal_canin.log_etl_run (run_id),
    CONSTRAINT fk_log_sku_match_upload FOREIGN KEY (upload_id) REFERENCES public.upload_progress (upload_id) ON DELETE SET NULL,
    CONSTRAINT fk_log_sku_match_channel_id FOREIGN KEY (channel_id) REFERENCES royal_canin.m_channel (channel_id),
    CONSTRAINT fk_log_sku_match_suggested_sku_id FOREIGN KEY (suggested_sku_id) REFERENCES royal_canin.m_sku (sku_id),
    CONSTRAINT fk_log_sku_match_resolved_sku_id FOREIGN KEY (resolved_sku_id) REFERENCES royal_canin.m_sku (sku_id)
)$sql$;
        EXECUTE $sql$CREATE UNIQUE INDEX uq_log_sku_match_pending ON royal_canin.log_sku_match (channel_id, merchant_sku, sku_code) WHERE status = 'PENDING'$sql$;
        EXECUTE $sql$CREATE INDEX ix_log_sku_match_upload_id ON royal_canin.log_sku_match (upload_id)$sql$;
        EXECUTE $sql$CREATE INDEX ix_log_sku_match_status ON royal_canin.log_sku_match (status)$sql$;
        EXECUTE $sql$CREATE TRIGGER trg_log_sku_match_updated_at BEFORE UPDATE ON royal_canin.log_sku_match
    FOR EACH ROW EXECUTE FUNCTION royal_canin.set_updated_at()$sql$;
        EXECUTE $sql$COMMENT ON TABLE royal_canin.log_sku_match IS 'listing baru (seller SKU & SKU platform belum ada di master) dicocokkan berdasarkan nama produk; PENDING = menunggu keputusan di UI (SKU sanitize: petakan ke saran atau buat SKU baru)'$sql$;
        EXECUTE $sql$COMMENT ON COLUMN royal_canin.log_sku_match.sku_code IS 'seller SKU bersih (R1); string kosong bila listing tanpa seller SKU'$sql$;
        EXECUTE $sql$COMMENT ON COLUMN royal_canin.log_sku_match.similarity_score IS 'cosine similarity TF-IDF n-gram karakter (3..5) nama ternormalisasi; cocok bila >= 0.55 (jarak <= 0.45)'$sql$;
        EXECUTE $sql$COMMENT ON COLUMN royal_canin.log_sku_match.candidates IS 'maks. 3 SKU master terdekat: [{sku_id, sku_master_code, name, score}]'$sql$;
        EXECUTE $sql$COMMENT ON COLUMN royal_canin.log_sku_match.status IS 'PENDING: menunggu review · MAPPED: dipetakan ke SKU yang ada · CREATED_NEW: dibuat sebagai SKU baru'$sql$;
        EXECUTE $sql$COMMENT ON COLUMN royal_canin.log_sku_match.resolved_by IS '''auto'' bila tidak ada nama yang mirip dan SKU baru dibuat otomatis oleh DAG, selain itu user yang memutuskan'$sql$;
        EXECUTE $sql$COMMENT ON COLUMN royal_canin.log_sku_match.first_order_at IS 'timestamptz: instan waktu absolut; tampil dalam Asia/Jakarta (WIB) pada session TimeZone default'$sql$;
        EXECUTE $sql$COMMENT ON COLUMN royal_canin.log_sku_match.last_order_at IS 'timestamptz: instan waktu absolut; tampil dalam Asia/Jakarta (WIB) pada session TimeZone default'$sql$;
        EXECUTE $sql$COMMENT ON COLUMN royal_canin.log_sku_match.resolved_at IS 'timestamptz: instan waktu absolut; tampil dalam Asia/Jakarta (WIB) pada session TimeZone default'$sql$;
        EXECUTE $sql$COMMENT ON COLUMN royal_canin.log_sku_match.created_at IS 'timestamptz: instan waktu absolut; tampil dalam Asia/Jakarta (WIB) pada session TimeZone default'$sql$;
        EXECUTE $sql$COMMENT ON COLUMN royal_canin.log_sku_match.updated_at IS 'timestamptz: instan waktu absolut; tampil dalam Asia/Jakarta (WIB) pada session TimeZone default'$sql$;
    END IF;
END
$do$;

COMMIT;
